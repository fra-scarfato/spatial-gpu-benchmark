#!/usr/bin/env python3
"""Split the generator's output into one LaTeX file per table, plus an index.

    analysis/tables/results-tables.py > tables.tex
    analysis/tables/split-tables.py tables.tex [--out DIR]

Each table is written to <out>/<label>.tex, where <label> is the table's LaTeX label, so a
chapter can `\\input` the tables it uses and a table can be moved or reordered without editing
its content. The index lists them in the order they appear.

Nothing is written unless every table block has a label: a table that cannot be named would be
dropped silently, and a silently missing table is worse than a failed run.
"""
import os
import re
import sys


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    src = args[0] if args else "-"
    out_dir = "/home/fscarfato/data/bench/aggregate/tables"
    for i, a in enumerate(sys.argv):
        if a == "--out" and i + 1 < len(sys.argv):
            out_dir = sys.argv[i + 1]
    text = sys.stdin.read() if src == "-" else open(src).read()

    blocks = re.findall(r"\\begin\{table\}.*?\\end\{table\}", text, re.S)
    if not blocks:
        sys.exit("  no table blocks found in {}".format(src))

    labelled, index = [], []
    for b in blocks:
        m = re.search(r"\\label\{([^}]*)\}", b)
        if not m:
            sys.exit("  a table has no label, refusing to write a partial set")
        labelled.append((m.group(1), b))

    os.makedirs(out_dir, exist_ok=True)
    for label, block in labelled:
        path = os.path.join(out_dir, label + ".tex")
        open(path, "w").write(block + "\n")
        index.append(label)
    with open(os.path.join(out_dir, "tables-index.tex"), "w") as fh:
        fh.write("% Generated by analysis/tables/split-tables.py. One file per table.\n")
        for label in index:
            fh.write("\\input{%s}\n" % label)
    print("  {} tables written to {}/".format(len(index), out_dir))
    print("  index: {}/tables-index.tex".format(out_dir))
    for label in index:
        print("    {:->34} {}.tex".format("", label))


if __name__ == "__main__":
    main()
